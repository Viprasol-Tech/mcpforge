"""Render a runnable MCP server source file from a :class:`ParsedAPI`.

The output is **emitted as text** — mcpforge never imports the ``mcp`` SDK
itself. The generated module uses the official low-level ``mcp.server`` stdio
pattern: a :class:`Server`, a ``list_tools`` handler returning every tool, and a
single ``call_tool`` dispatcher that echoes the received arguments (a safe stub
you replace with real HTTP calls).

Every rendered file is guaranteed to ``compile()`` — this is asserted in tests.
"""

from __future__ import annotations

import json

from .models import ParsedAPI, ToolSpec

_HEADER = '''"""Auto-generated MCP server for {title} (v{version}).

Generated by mcpforge (https://github.com/Viprasol-Tech/mcpforge).
Do not edit by hand — re-run mcpforge against your OpenAPI spec instead.

Run it::

    pip install mcp
    python {module_name}.py
"""

from __future__ import annotations

import asyncio
import json
from typing import Any

import mcp.types as types
from mcp.server import Server
from mcp.server.stdio import stdio_server

app: Server = Server({server_name!r})

# Static catalogue of tools generated from the OpenAPI document.
_TOOLS: list[types.Tool] = [
'''

_FOOTER = '''

@app.list_tools()
async def list_tools() -> list[types.Tool]:
    """Return every tool generated from the OpenAPI spec."""
    return _TOOLS


# Maps each tool name to its (method, path) so the dispatcher can build a request.
_ROUTES: dict[str, dict[str, str]] = {routes_json}


@app.call_tool()
async def call_tool(name: str, arguments: dict[str, Any]) -> list[types.TextContent]:
    """Dispatch a tool call.

    This is a stub: it echoes the resolved route and the arguments it received.
    Replace the body with a real HTTP call (e.g. httpx) to your backend.
    """
    route = _ROUTES.get(name)
    if route is None:
        raise ValueError(f"unknown tool: {{name}}")
    payload = {{
        "tool": name,
        "method": route["method"],
        "path": route["path"],
        "arguments": arguments,
    }}
    return [types.TextContent(type="text", text=json.dumps(payload, indent=2))]


async def _main() -> None:
    async with stdio_server() as (read_stream, write_stream):
        await app.run(read_stream, write_stream, app.create_initialization_options())


def main() -> None:
    """Console entry point — serve over stdio."""
    asyncio.run(_main())


if __name__ == "__main__":
    main()
'''


def _render_tool_entry(tool: ToolSpec) -> str:
    """Render one ``types.Tool(...)`` literal for the ``_TOOLS`` list."""

    schema_literal = json.dumps(tool.input_schema, indent=8, sort_keys=False)
    # Re-indent the multi-line JSON so it sits nicely inside the call.
    schema_lines = schema_literal.splitlines()
    if len(schema_lines) > 1:
        schema_literal = (
            schema_lines[0] + "\n" + "\n".join("        " + line for line in schema_lines[1:])
        )
    return (
        "    types.Tool(\n"
        f"        name={tool.name!r},\n"
        f"        description={tool.description!r},\n"
        f"        inputSchema={schema_literal},\n"
        "    ),\n"
    )


def render_server(parsed: ParsedAPI, *, module_name: str = "server") -> str:
    """Render a complete, ``compile()``-clean MCP server module as a string.

    Args:
        parsed: The parsed API to generate tools for.
        module_name: Filename stem used in the generated docstring.

    Returns:
        Python source for a stdio MCP server exposing one tool per operation.
    """

    server_name = _server_slug(parsed.title)
    parts: list[str] = [
        _HEADER.format(
            title=parsed.title,
            version=parsed.version,
            module_name=module_name,
            server_name=server_name,
        )
    ]
    for tool in parsed.tools:
        parts.append(_render_tool_entry(tool))
    parts.append("]\n")

    routes = {t.name: {"method": t.method, "path": t.path} for t in parsed.tools}
    routes_json = json.dumps(routes, indent=4)
    # Indented routes need their continuation lines aligned at module level (none).
    parts.append(_FOOTER.format(routes_json=routes_json))

    return "".join(parts)


def _server_slug(title: str) -> str:
    """Make a friendly lowercase server name from a document title."""

    slug = "".join(c if c.isalnum() else "-" for c in title.lower()).strip("-")
    slug = "-".join(filter(None, slug.split("-")))
    return slug or "mcpforge-server"
